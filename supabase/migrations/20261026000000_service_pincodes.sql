-- The PIN codes we serve, managed from the admin panel so new ones (for example towns around Bengaluru) can be added later.
-- Everyone can read the list (the website needs it); only the owner can change it. active = false pauses a PIN code.
create table if not exists public.service_pincodes (
  pin        text primary key check (pin ~ '^[0-9]{6}$'),
  name       text not null check (char_length(name) between 2 and 60),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.service_pincodes enable row level security;
drop policy if exists service_pincodes_read on public.service_pincodes;
create policy service_pincodes_read on public.service_pincodes for select to anon, authenticated using (true);
drop policy if exists service_pincodes_owner_insert on public.service_pincodes;
create policy service_pincodes_owner_insert on public.service_pincodes for insert to authenticated with check (public.is_owner());
drop policy if exists service_pincodes_owner_update on public.service_pincodes;
create policy service_pincodes_owner_update on public.service_pincodes for update to authenticated using (public.is_owner()) with check (public.is_owner());
drop policy if exists service_pincodes_owner_delete on public.service_pincodes;
create policy service_pincodes_owner_delete on public.service_pincodes for delete to authenticated using (public.is_owner());

